# ROCK BASE Windows-first Docker setup.
# Creates backend/.env only when missing. Never deletes volumes or rotates an existing key.
[CmdletBinding()]
param(
  [string]$DashboardUrl = 'http://localhost:5173',
  [int]$ReadinessAttempts = 30,
  [int]$ReadinessDelaySeconds = 2
)

$ErrorActionPreference = 'Stop'
$ProjectRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$EnvPath = Join-Path $ProjectRoot 'backend/.env'

function Write-Step([string]$Message) { Write-Host "→ $Message" -ForegroundColor Cyan }
function Write-Pass([string]$Message) { Write-Host "[PASS] $Message" -ForegroundColor Green }
function New-HexSecret([int]$ByteCount) {
  $bytes = New-Object byte[] $ByteCount
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
  return ($bytes | ForEach-Object { $_.ToString('x2') }) -join ''
}
function New-Password([int]$Length = 24) {
  $alphabet = 'abcdefghijkmnopqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789!@#$%*-_'
  $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
  $chars = for ($i = 0; $i -lt $Length; $i++) {
    $buffer = New-Object byte[] 4
    $rng.GetBytes($buffer)
    $alphabet[[BitConverter]::ToUInt32($buffer, 0) % $alphabet.Length]
  }
  return -join $chars
}

Write-Step 'Checking Docker command'
if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
  throw 'Docker Desktop is required. Install Docker Desktop, start it, then run this script again.'
}
& docker version --format '{{.Server.Version}}' | Out-Null
Write-Pass 'Docker daemon is reachable'
& docker compose version | Out-Null
Write-Pass 'Docker Compose is available'

$createdEnv = $false
$bootstrapPassword = $null
if (-not (Test-Path $EnvPath)) {
  Write-Step 'Creating local RockBase configuration'
  $jwtSecret = New-HexSecret 64
  $encryptionKey = New-HexSecret 32
  $bootstrapPassword = New-Password
  $bootstrapToken = New-HexSecret 32
  @"
# Generated by setup-rockbase.ps1 for this local installation.
# Keep this file private. Do not rotate ENCRYPTION_KEY after sessions exist.
PORT=3010
FRONTEND_URL="http://localhost:5173"
BACKEND_URL="http://localhost:3010"
AUTOMATION_ENABLED=false
DATABASE_URL="file:./dev.db"
REDIS_HOST="127.0.0.1"
REDIS_PORT=6379
MAX_BULK_SESSION_CHECK=3
SESSION_HEALTH_CHECK_CONCURRENCY=2
JWT_SECRET="$jwtSecret"
JWT_EXPIRES_IN="24h"
ENCRYPTION_KEY="$encryptionKey"
# DATA RECOVERY CRITICAL: preserve this exact key with the database backup.
BOOTSTRAP_ADMIN_ENABLED=true
BOOTSTRAP_ADMIN_EMAIL="admin@rockbase.local"
BOOTSTRAP_ADMIN_PASSWORD="$bootstrapPassword"
BOOTSTRAP_ADMIN_TOKEN="$bootstrapToken"
GEMINI_API_KEY=""
GEMINI_MODEL="gemini-flash-latest"
VISION_PROVIDER="auto"
GEMINI_VISION_MODEL="gemini-flash-latest"
OPENAI_API_KEY=""
OPENAI_VISION_MODEL="gpt-4o-mini"
"@ | ForEach-Object { [System.IO.File]::WriteAllText($EnvPath, $_, (New-Object System.Text.UTF8Encoding($false))) }
  $createdEnv = $true
  Write-Pass 'Created backend/.env and generated local secrets'
} else {
  Write-Pass 'Existing backend/.env preserved without changes'
}

Write-Step 'Building and starting RockBase'
Push-Location $ProjectRoot
try {
  & docker compose up -d --build
  if ($LASTEXITCODE -ne 0) { throw 'Docker Compose failed to start RockBase.' }
} finally {
  Pop-Location
}

Write-Step 'Waiting for RockBase readiness'
$ready = $false
for ($attempt = 1; $attempt -le $ReadinessAttempts; $attempt++) {
  try {
    $response = Invoke-WebRequest -UseBasicParsing -Uri 'http://localhost:3010/readyz' -TimeoutSec 5
    if ($response.StatusCode -eq 200) { $ready = $true; break }
  } catch {}
  Start-Sleep -Seconds $ReadinessDelaySeconds
}
if (-not $ready) {
  throw 'RockBase containers started but readiness did not pass. Run: docker compose logs -f backend'
}
Write-Pass 'RockBase backend is ready'

if ($createdEnv) {
  Write-Step 'Creating the one-time local administrator'
  try {
    Invoke-WebRequest -UseBasicParsing -Method Post -Uri 'http://localhost:3010/api/auth/bootstrap-admin' -Headers @{ 'x-bootstrap-token' = $bootstrapToken } | Out-Null
    Write-Pass 'Local administrator created'
  } catch {
    throw 'RockBase is ready, but first administrator bootstrap failed. Check docker compose logs -f backend before retrying.'
  }
  Write-Host ''
  Write-Host 'First login (save this password now):' -ForegroundColor Yellow
  Write-Host 'Email:    admin@rockbase.local'
  Write-Host "Password: $bootstrapPassword"
}

Write-Host ''
Write-Host 'RockBase ready' -ForegroundColor Green
Write-Host "Open: $DashboardUrl"
Write-Host 'For an existing installation upgrade, use docs/UPGRADE.md and scripts/preflight-upgrade.ps1. Do not use this script to replace an existing backend/.env.'
